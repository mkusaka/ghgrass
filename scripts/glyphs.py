"""Rasterizes the PNG's text glyphs into src/glyphs.ts.

Workers have no fonts and a real rasterizer (resvg-wasm) costs ~25 ms of CPU per image,
over the free plan's 10 ms, so the few glyphs the PNG needs are prerendered at 2x.

    uv run scripts/glyphs.py noto-sans-latin-400-normal.woff > src/glyphs.ts

The font is Noto Sans Regular from @fontsource/noto-sans 5.3.0 (SIL Open Font License 1.1).
"""

import base64
import json
import math
import sys

from PIL import Image, ImageDraw, ImageFont

# Font size (CSS px, 1x) -> the text drawn at that size.
TEXTS = {
    12: "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec Mon Wed Fri Less More",
    16: "0123456789, contributions in the last year",
}
SCALE = 2

sizes = {}
for size, text in TEXTS.items():
    font = ImageFont.truetype(sys.argv[1], size * SCALE)
    glyphs = {}
    for char in sorted(set(text)):
        # Drawn with the baseline at y = 0 of a canvas offset by `pad` on each side.
        pad = size * SCALE
        image = Image.new("L", (pad * 3, pad * 3))
        ImageDraw.Draw(image).text((pad, pad * 2), char, font=font, fill=255, anchor="ls")
        box = image.getbbox() or (pad, pad * 2, pad, pad * 2)
        crop = image.crop(box)
        glyphs[char] = {
            "advance": font.getlength(char),
            "x": box[0] - pad,
            "y": box[1] - pad * 2,
            "width": crop.width,
            "alpha": base64.b64encode(crop.tobytes()).decode(),
        }
    sizes[size] = glyphs

print("// Generated by scripts/glyphs.py from Noto Sans (SIL Open Font License 1.1). Do not edit.")
print("// Per CSS font size: glyphs rasterized at 2x, x/y from the pen position on the baseline.")
print(f"export const glyphs: Record<number, Record<string, {{ advance: number; x: number; y: number; width: number; alpha: string }}>> = {json.dumps(sizes, indent=1)};")
